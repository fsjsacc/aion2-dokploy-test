var routeLocaleByCode = Object.fromEntries(siteLocales.map((locale) => [siteLocaleConfig[locale].code, locale]));
var supportedLocaleCodes = new Set(siteLocales.map((locale) => siteLocaleConfig[locale].code));
function isLocale(value) {
	return value !== null && supportedLocaleCodes.has(value);
}
function routeLocaleForMapLocale(locale) {
	return routeLocaleByCode[locale];
}
function mapDataLocaleForLocale(locale) {
	return siteLocaleConfig[routeLocaleForMapLocale(locale)].mapDataLocale;
}
function numberLocaleForMapLocale(locale) {
	if (locale === "en") return "en-US";
	if (locale === "ko") return "ko-KR";
	return locale;
}
